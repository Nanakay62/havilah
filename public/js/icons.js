  /**
   * Accessible Mobile Sidebar Drawer Controller
   */
  function initMobileDrawer(sidebarId = 'appSidebar', toggleBtnId = 'sidebarToggleBtn', backdropId = 'sidebarBackdrop') {
    const sidebar = document.getElementById(sidebarId);
    const toggleBtn = document.getElementById(toggleBtnId);
    const backdrop = document.getElementById(backdropId);

    if (!sidebar || !toggleBtn) return;

    function openDrawer() {
      sidebar.classList.add('is-open');
      if (backdrop) backdrop.classList.add('is-open');
      toggleBtn.setAttribute('aria-expanded', 'true');
      document.body.style.overflow = 'hidden';
      const firstNav = sidebar.querySelector('button, a, [tabindex="0"]');
      if (firstNav) firstNav.focus();
    }

    function closeDrawer() {
      sidebar.classList.remove('is-open');
      if (backdrop) backdrop.classList.remove('is-open');
      toggleBtn.setAttribute('aria-expanded', 'false');
      document.body.style.overflow = '';
      toggleBtn.focus();
    }

    toggleBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      const isOpen = sidebar.classList.contains('is-open');
      if (isOpen) {
        closeDrawer();
      } else {
        openDrawer();
      }
    });

    if (backdrop) {
      backdrop.addEventListener('click', closeDrawer);
    }

    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape' && sidebar.classList.contains('is-open')) {
        closeDrawer();
      }
    });
  }

  /**
   * Accessible Modal Focus Trap
   */
  function trapModalFocus(modalEl, closeCallback) {
    if (!modalEl) return () => {};

    const focusableEls = modalEl.querySelectorAll(
      'button:not([disabled]), [href], input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])'
    );
    const firstFocusable = focusableEls[0];
    const lastFocusable = focusableEls[focusableEls.length - 1];

    if (firstFocusable) firstFocusable.focus();

    function handleKey(e) {
      if (e.key === 'Escape' && typeof closeCallback === 'function') {
        closeCallback();
        return;
      }
      if (e.key === 'Tab') {
        if (e.shiftKey) {
          if (document.activeElement === firstFocusable) {
            e.preventDefault();
            lastFocusable?.focus();
          }
        } else {
          if (document.activeElement === lastFocusable) {
            e.preventDefault();
            firstFocusable?.focus();
          }
        }
      }
    }

    modalEl.addEventListener('keydown', handleKey);
    return () => modalEl.removeEventListener('keydown', handleKey);
  }

